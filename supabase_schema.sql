
create table if not exists public.root_locus_learning_submissions (
 id bigint generated by default as identity primary key,
 submitted_at timestamptz not null default now(),
 student_name text not null,
 roll_no text not null,
 experiment text not null,
 numerator text,
 denominator text,
 predicted_poles text,
 predicted_zeros text,
 predicted_real_axis text,
 predicted_centroid double precision,
 predicted_stable_range text,
 prediction text,
 real_axis_explanation text,
 asymptote_learning text,
 breakaway_learning text,
 stability_conclusion text,
 reflection text,
 verified_stable_region text,
 concept_score integer
);

alter table public.root_locus_learning_submissions enable row level security;

create policy "allow root locus learning insert"
on public.root_locus_learning_submissions
for insert to anon, authenticated
with check (true);

create policy "allow root locus learning select"
on public.root_locus_learning_submissions
for select to anon, authenticated
using (true);
